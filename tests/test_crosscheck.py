"""Bit-exact cross-check against amy's C implementation.

tests/data/crosscheck_reference.json holds the accumulators and scores
produced by amy's own neural_net.c (branch
feature/neural-net-with-clamped-relu, src/nn_crosscheck.c) for a random
in-range network generated with a fixed seed.  The Python
QuantizedNet must reproduce every value, including int16 wrap-around,
the [0, 64] and [0, 8192] clamps, and the two-step rounded output
transform.
"""

import json
from pathlib import Path

import numpy as np
import pytest

from amy_training_nnue.bpd import BLACK, WHITE
from amy_training_nnue.features import feature_indices
from amy_training_nnue.quantize import QuantizedNet, quantize_parameters

DATA = Path(__file__).parent / "data" / "crosscheck_reference.json"
MAX_FEATURES = 32

# Experiment branch: this architecture (ACCUMULATOR_SIZE=128,
# HIDDEN_SIZE_1=16, HIDDEN_SIZE_2=32) has no C counterpart yet.  The
# reference in crosscheck_reference.json was generated by amy's
# neural_net.c for the 256/32/32 architecture.  Re-enable this file
# once amy's C is switched to the reduced sizes (and the reference
# regenerated with tools/make_crosscheck_reference.py; _make_network
# and the tool's shape constants must be updated to match).
pytestmark = pytest.mark.skip(reason="C cross-check reference is for the 256/32/32 architecture; see module comment")


def _make_network(seed: int) -> QuantizedNet:
    """Regenerate the deterministic random network from the reference.

    Must mirror tools/make_crosscheck_reference.py exactly (same seed,
    same draw order; input_w is drawn from [-1, 1], the range
    representable by int8 at scale 64).
    """
    rng = np.random.default_rng(seed)
    params = {
        "input_w": rng.uniform(-1, 1, (40960, 256)),
        "input_b": rng.uniform(-1, 1, (256,)),
        "h1_w": rng.uniform(-2, 2, (512, 32)),
        "h1_b": rng.uniform(-2, 2, (32,)),
        "h2_w": rng.uniform(-2, 2, (32, 32)),
        "h2_b": rng.uniform(-2, 2, (32,)),
        "out_w": rng.uniform(-1, 1, (32,)),
        "out_b": rng.uniform(-1, 1, (1,)),
    }
    return QuantizedNet.from_arrays(quantize_parameters(params))


def _board_from_epd(epd: str) -> np.ndarray:
    pieces = {
        "P": (1, 1),
        "N": (1, 2),
        "B": (1, 3),
        "R": (1, 4),
        "Q": (1, 5),
        "K": (1, 6),
        "p": (-1, 1),
        "n": (-1, 2),
        "b": (-1, 3),
        "r": (-1, 4),
        "q": (-1, 5),
        "k": (-1, 6),
    }
    board = np.zeros(64, dtype=np.int8)
    rows = epd.split(" ")[0].split("/")
    for rank, row in enumerate(rows):
        real_rank = 7 - rank
        file = 0
        for ch in row:
            if ch.isdigit():
                file += int(ch)
            else:
                color, piece = pieces[ch]
                board[real_rank * 8 + file] = color * piece
                file += 1
    return board


def _pad(feat: np.ndarray) -> np.ndarray:
    out = np.full((1, MAX_FEATURES), -1, dtype=np.int32)
    out[0, : len(feat)] = feat
    return out


@pytest.fixture(scope="module")
def reference():
    return json.loads(DATA.read_text())


def test_accumulators_match_c(reference):
    """Raw (int16 wrap-around) accumulators must equal amy's."""
    ref = reference["positions"][0]
    qnet = _make_network(reference["seed"])
    board = _board_from_epd(ref["epd"])
    fw, fb = feature_indices(board)
    acc_w = qnet.accumulator(_pad(fw))[0]
    acc_b = qnet.accumulator(_pad(fb))[0]
    assert np.array_equal(acc_w, np.asarray(ref["acc_w"], dtype=np.int32))
    assert np.array_equal(acc_b, np.asarray(ref["acc_b"], dtype=np.int32))


def test_scores_match_c(reference):
    """Scores must equal amy's, for every reference position."""
    qnet = _make_network(reference["seed"])
    for ref in reference["positions"]:
        board = _board_from_epd(ref["epd"])
        turn = WHITE if " w " in ref["epd"] else BLACK
        assert turn == ref["turn"]
        fw, fb = feature_indices(board)
        score = int(
            qnet.evaluate(_pad(fw), _pad(fb), np.array([turn], dtype=np.uint8))[0]
        )
        assert score == ref["score"], f"{ref['epd']}: {score} != {ref['score']}"
